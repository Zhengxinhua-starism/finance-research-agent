def _doc_id(title: str) -> str:
    """由标题确定性生成 doc_id，保证重复建库时 upsert 而不是新增。"""
    return "kb_" + hashlib.sha1(title.encode("utf-8")).hexdigest()[:12]


def _document(title: str, content: str, **metadata: Any) -> Document:
    return Document(
        doc_id=_doc_id(title),
        content=f"# {title}\n\n{content.strip()}",
        metadata={"title": title, "source": "手工整理", **metadata},
    )


